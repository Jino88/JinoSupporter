# Common builder
def make_doc(name, title, model, date, dept, marker, line, report_type,
             primary, aliases, related, parts, processes, purpose, content):
    return {
        'document_id': 'doc',
        'source_file': name,
        'source_sheet': '',
        'title': title,
        'model': model,
        'report_date': date,
        'department': dept,
        'marker': marker,
        'line': line,
        'report_type': report_type,
        'primary_defect': {'canonical_name': primary, 'aliases_in_document': aliases},
        'related_defects': related,
        'parts': parts,
        'processes': processes,
        'purpose': purpose,
        'content': content,
        'source_cells': {'title': [], 'date': [], 'purpose': [], 'content': []},
    }


def commit(name, doc, conds, results, concls, hints, defect_name, when_user_asks,
           limitations, conf, assumptions, warnings, rationale,
           tr_ko_doc, tr_en_doc, tr_vi_doc,
           tr_ko_concl, tr_en_concl, tr_vi_concl,
           tr_ko_hints, tr_en_hints, tr_vi_hints,
           tr_ko_log, tr_en_log, tr_vi_log):
    result = {
        'schema_version': '0.1',
        'document': doc,
        'test_conditions': conds,
        'results': results,
        'conclusions': concls,
        'troubleshooting_index': {
            'defect_name': defect_name,
            'when_user_asks': when_user_asks,
            'suggested_checks': hints,
            'limitations': limitations,
        },
        'ai_extraction_log': {
            'confidence': conf,
            'assumptions': assumptions,
            'warnings': warnings,
            'decision_rationale': rationale,
        },
    }
    tr_ko = {'document': tr_ko_doc, 'conclusions': tr_ko_concl, 'hints': tr_ko_hints, 'log': tr_ko_log}
    tr_en = {'document': tr_en_doc, 'conclusions': tr_en_concl, 'hints': tr_en_hints, 'log': tr_en_log}
    tr_vi = {'document': tr_vi_doc, 'conclusions': tr_vi_concl, 'hints': tr_vi_hints, 'log': tr_vi_log}
    ok = h.commit_dataset(name, result, tr_ko, tr_en, tr_vi)
    print(('OK ' if ok else 'FAIL ') + name)
    return ok


